/**
 * `cookiemunch scan-source [dir]`: the first-party cookie and storage names a codebase sets, found statically
 * (no browser, no key), as cookiemunch.json cookie rows to declare. And `cookiemunch types`: the site's
 * categories as a TypeScript declaration that narrows the category arguments of `@cookiemunch/react`.
 */

export type SourceRowType = 'cookie' | 'localStorage' | 'sessionStorage';

/** A cookiemunch.json cookie row, with the category left for a person to choose and where the name was seen. */
export interface SourceRow {
  name: string;
  type: SourceRowType;
  category: null;
  files: string[];
}

export const SOURCE_EXTENSIONS = ['.js', '.ts', '.jsx', '.tsx', '.vue', '.svelte', '.html'];
const SKIP_DIRS = new Set(['node_modules', 'dist', '.next', '.git']);

/** Directories a scan never walks into. */
export function skipDir(name: string): boolean {
  return SKIP_DIRS.has(name);
}

const Q = '[\'"`]';
const NAME = '([^\'"`\\s=;]+)';
const PATTERNS: Array<[RegExp, SourceRowType]> = [
  // document.cookie = "name=…"
  [new RegExp(`document\\.cookie\\s*=\\s*${Q}\\s*([^'"\`\\s=;]+)=`, 'g'), 'cookie'],
  // cookies.set('name' (js-cookie's Cookies.set, Next's res.cookies.set) and Next's cookies().set('name'
  [new RegExp(`\\b[Cc]ookies(?:\\(\\s*\\))?\\.set\\(\\s*${Q}${NAME}${Q}`, 'g'), 'cookie'],
  [new RegExp(`\\blocalStorage\\.setItem\\(\\s*${Q}${NAME}${Q}`, 'g'), 'localStorage'],
  [new RegExp(`\\bsessionStorage\\.setItem\\(\\s*${Q}${NAME}${Q}`, 'g'), 'sessionStorage'],
];

/** The rows found in these files (paths as given), one per name and type, sorted by name. */
export function scanSourceFiles(files: Array<{ path: string; text: string }>): SourceRow[] {
  const rows = new Map<string, SourceRow>();
  for (const f of files) {
    for (const [re, type] of PATTERNS) {
      for (const m of f.text.matchAll(re)) {
        // A template literal's interpolation becomes a prefix wildcard, as declarations spell it (`cart_*`).
        const name = m[1]!.replace(/\$\{.*$/, '*');
        if (!name || name === '*') continue;
        const key = `${type}\u0000${name}`;
        const row = rows.get(key) ?? { name, type, category: null, files: [] };
        if (!row.files.includes(f.path)) row.files.push(f.path);
        rows.set(key, row);
      }
    }
  }
  return [...rows.values()]
    .map((r) => ({ ...r, files: r.files.sort() }))
    .sort((a, b) => a.name.localeCompare(b.name) || a.type.localeCompare(b.type));
}

const STANDARD = ['preferences', 'statistics', 'marketing'] as const;

/** The category ids a site offers: necessary, the standard ones not switched off, its suite and custom ids. */
export function offeredCategories(config: Record<string, unknown>): string[] {
  const cats = (config.categories ?? {}) as Record<string, unknown>;
  const out = ['necessary'];
  for (const id of STANDARD) if ((cats[id] as { enabled?: unknown } | undefined)?.enabled !== false) out.push(id);
  for (const id of Array.isArray(cats.suite) ? cats.suite : []) if (typeof id === 'string' && !out.includes(id)) out.push(id);
  for (const c of Array.isArray(cats.custom) ? cats.custom : []) {
    const id = (c as { id?: unknown; enabled?: unknown } | null)?.id;
    if (typeof id === 'string' && (c as { enabled?: unknown }).enabled !== false && !out.includes(id)) out.push(id);
  }
  return out;
}

/** The `.d.ts` `cookiemunch types` writes. */
export function categoryTypes(cbid: string, categories: string[], modules: string[] = ['@cookiemunch/react']): string {
  const lit = (c: string) => `'${c.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  return [
    `// Generated by \`cookiemunch types\` for site ${cbid}. Re-run it when the site's categories change.`,
    `export type CookieMunchCategory = ${categories.map(lit).join(' | ')};`,
    '',
    '// Category arguments (useConsentValue, useConsentCookie, consentState, onConsent, hasConsent) accept only these.',
    ...modules.flatMap((m) => [
      `declare module '${m}' {`,
      '  interface CookieMunchCategories {',
      ...categories.map((c) => `    ${lit(c)}: true;`),
      '  }',
      '}',
    ]),
    '',
  ].join('\n');
}
